local function trim(value)
  return tostring(value or "")
    :gsub("^%s+", "")
    :gsub("%s+$", "")
end

-- TODO unused, superseded by placeholders.parse_categories
local function parse_commons_categories(text) -- luacheck: ignore

  local categories = {}

  -- Categories may be separated by semicolons or newlines.
  -- Examples:
  --
  --   Category one;Alice Albert;WikiCon 2026
  --
  -- or:
  --
  --   Category one
  --   Alice Albert
  --   WikiCon 2026

  text = tostring(text or "")

  -- Treat line endings exactly like semicolons.
  text = text:gsub("\r\n", ";")
  text = text:gsub("[\r\n]", ";")

  for item in text:gmatch("[^;]+") do

    item = trim(item)

    -- Be liberal about accepting complete Commons category syntax.
    item = item:gsub(
      "^%[%[[Cc]ategory:%s*",
      ""
    )

    item = item:gsub("%]%]$", "")
    item = trim(item)

    if item ~= "" then
      table.insert(categories, item)
    end
  end

  return categories
end

local function get_new_commons_categories(image)

  local categories = {}
  local seen = {}

  local function add(category)

    category = trim(category)

    if category ~= ""
        and not seen[category] then

      seen[category] = true

      table.insert(
        categories,
        category
      )
    end
  end

  -- Per-image Commons categories
  -- TODO stored_value is unused, the inner loop repeats the same lookup
  for _, stored_value in ipairs( -- luacheck: ignore
    placeholders.get_categories(image)
  ) do

    for _, category in ipairs(
      placeholders.get_categories(image)
    ) do
      add(category)
    end
  end

  -- Global Commons categories
  for _, category in ipairs(
    placeholders.parse_categories(
      global_categories_widget.text
    )
  ) do
    add(category)
  end

  return categories
end

local function get_dtmediawiki_descriptions(image)

  local descriptions = {}

  local de =
    trim(
      placeholders.get_metadata(
        image,
        "description_de"
      )
    )

  local en =
    trim(
      placeholders.get_metadata(
        image,
        "description_en"
      )
    )

  if de ~= "" then
    table.insert(
      descriptions,
      "{{de|1=" .. de .. "}}"
    )
  end

  if en ~= "" then
    table.insert(
      descriptions,
      "{{en|1=" .. en .. "}}"
    )
  end

  for _, description in ipairs(
    placeholders.get_field(
      image,
      "description_other"
    )
  ) do

    description = trim(description)

    if description ~= "" then
      table.insert(
        descriptions,
        description
      )
    end
  end

  return table.concat(descriptions, "\n")
end

-- Get per-image values of a multi-value metadata field, trimmed and
-- without empty entries.
local function get_field_values(image, name)

  local result = {}

  for _, value in ipairs(
    placeholders.get_field(image, name)
  ) do

    value = trim(value)

    if value ~= "" then
      table.insert(result, value)
    end
  end

  return result
end

-- Other fields from the metadata panel. Wikidata items are shown as
-- an additional {{Information field}}.
local function get_dtmediawiki_other_fields(image)

  local fields =
    get_field_values(image, "other_fields")

  for _, item in ipairs(
    get_field_values(image, "wikidata")
  ) do

    if item:match("^[Qq]%d+$") then
      item = "{{Q|" .. item:upper() .. "}}"
    end

    table.insert(
      fields,
      "{{Information field|name=Wikidata|value=" .. item .. "}}"
    )
  end

  return table.concat(fields)
end

-- Other versions from the metadata panel merged with the gallery
-- generated from "alt:" tags.
local function get_other_versions(image, tmp_img_fn)

  local gallery =
    get_alt_images(image, tmp_img_fn)

  local files = {}

  for _, file in ipairs(
    get_field_values(image, "other_versions")
  ) do

    file = trim(
      file:gsub("^%[%[", "")
          :gsub("%]%]$", "")
          :gsub("^[Ff]ile:", "")
    )

    if file ~= "" then
      table.insert(files, file)
    end
  end

  if #files == 0 then
    return gallery
  end

  if gallery == "" then
    return "<gallery showfilename=yes>\n"
      .. table.concat(files, "\n")
      .. "\n</gallery>"
  end

  return (gallery:gsub(
    "</gallery>$",
    function()
      return table.concat(files, "\n") .. "\n</gallery>"
    end
  ))
end

-- Templates from the metadata panel, wrapped in {{...}} if needed.
local function get_dtmediawiki_templates(image)

  local templates = {}

  for _, template in ipairs(
    get_field_values(image, "templates")
  ) do

    if template:sub(1, 2) ~= "{{" then
      template = "{{" .. template .. "}}"
    end

    table.insert(templates, template)
  end

  return templates
end

-- Generate an image page with all required info from tags, metadata, and such.
local function make_image_page(image, tmp_img_fn)
  local discarded_tags = {}
  local imgpg = { "=={{int:filedesc}}==\n{{Information" }

local new_descriptions =
  get_dtmediawiki_descriptions(image)

if new_descriptions ~= "" then

  table.insert(
    imgpg,
    "|description=" .. new_descriptions
      .. get_intl_descriptions(
        image,
        discarded_tags
      )
  )
else

  -- Legacy dtMediaWiki behaviour
  table.insert(
    imgpg,
    "|description={{"
      .. language_widget.text
      .. "|1="
      .. substitute_keywords(
        get_description(image),
        image
      )
      .. "}}"
      .. get_intl_descriptions(
        image,
        discarded_tags
      )
  )

end

  local date = image.exif_datetime_taken
  date = date:gsub("(%d%d%d%d):(%d%d):(%d%d)", "%1-%2-%3") -- format date in ISO 8601 / RFC 3339
  table.insert(imgpg, "|date=" .. date)
  table.insert(imgpg, "|source={{own}}")
  local author = dt.preferences.read(preferences_prefix, "authorpattern", "string")
  author = substitute_keywords(author, image)
  table.insert(imgpg, "|author=" .. author)
  table.insert(imgpg, '|other fields = ' .. get_other_fields(image, discarded_tags)
    .. get_dtmediawiki_other_fields(image))
  table.insert(imgpg, '|other versions = ' .. get_other_versions(image, tmp_img_fn))
  table.insert(imgpg, "}}")
  if image.latitude ~= nil and image.longitude ~= nil then
    table.insert(imgpg, "{{Location |1=" .. string.gsub(image.latitude, ",", ".")
      .. " |2=" .. string.gsub(image.longitude, ",", ".") .. " }}")
  end

table.insert(
  imgpg,
  "=={{int:license-header}}=="
)

table.insert(
  imgpg,
  "{{self|" .. get_license(image) .. "}}"
)

for _, template in ipairs(
  get_dtmediawiki_templates(image)
) do
  table.insert(imgpg, template)
end

