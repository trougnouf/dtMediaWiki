local preview_button = -- luacheck: ignore
  dt.new_widget("button") {
    label = translate("Write Commons preview"),

    clicked_callback = function()

      local images = dt.gui.selection()

      if not images or #images == 0 then
        dt.print("dtMediaWiki: no image selected")
        return
      end

      MetadataUI.save()

      local image = images[1]

      -- make_image_page() needs the temporary filename only for
      -- the existing "other versions" handling.
      local preview =
        make_image_page(
          image,
          image.filename or ""
        )

      local home = os.getenv("HOME") or os.getenv("USERPROFILE") or "."
      local filename =
        home .. "/dtmediawiki-commons-preview.txt"

      local f, err = io.open(filename, "w")

      if not f then
        dt.print(
          "dtMediaWiki: unable to write preview: "
          .. tostring(err)
        )
        return
      end

      f:write(preview)
      f:write("\n")
      f:close()

      dt.print(
        "dtMediaWiki: Commons preview written to "
        .. filename
      )
    end
  }

