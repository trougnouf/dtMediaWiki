local function parse_categories(text)

  local result = {}

  for line in tostring(text or ""):gmatch("[^\r\n]+") do

    line =
      line:gsub("^%s+", "")
          :gsub("%s+$", "")

    -- Be forgiving if the user entered Commons syntax.
    line =
      line:gsub(
        "^%[%[[Cc]ategory:%s*",
        ""
      )

    line =
      line:gsub("%]%]$", "")

    if line ~= "" then
      table.insert(result, line)
    end
  end

  return result
end

local function get_commons_categories(image)

  local result = {}
  local seen = {}

  local function add(value)

    value =
      tostring(value or "")
        :gsub("^%s+", "")
        :gsub("%s+$", "")

    if value ~= "" and not seen[value] then
      seen[value] = true
      table.insert(result, value)
    end
  end

  ---------------------------------------------------------------------
  -- Image-specific categories
  ---------------------------------------------------------------------

  for _, category in ipairs(
    placeholders.get_categories(image)
  ) do
    add(category)
  end

  ---------------------------------------------------------------------
  -- Global export categories
  ---------------------------------------------------------------------

  for _, category in ipairs(
    parse_categories(
      global_categories_widget.text
    )
  ) do
    add(category)
  end

  return result
end

